/// Which bundled crest belongs to a club's name (pure: no file is read here).
///
/// The crests are the PNG files under `apps/mobile/assets/team_logos/`, one
/// per slug (`al-hilal.png`); the server image carries the same folder for
/// the publisher's pictures. The tables below are those of the app's
/// `team_logo_assets.dart` (the Arabic names and spellings its fixture
/// cards know, and the English provider names), kept equal by
