  /// The slug of [clubName]'s crest: an Arabic name or spelling the app
  /// knows, or an English provider name (`Kauno Žalgiris`); null when
  /// the club has no crest on file.
  static String? slugFor(String? clubName) {
    if (clubName == null) {
      return null;
    }
    final trimmed = clubName.trim();
    if (trimmed.isEmpty) {
      return null;
    }
    final aliased =
        _arabicAliases[trimmed] ?? _normalizedAliases[normalizeArabic(trimmed)];
    final slugified = slugOf(trimmed);
    final slug = aliased ?? _worldCupAliases[slugified] ?? slugified;
    return slug.isNotEmpty && _slugs.contains(slug) ? slug : null;
  }

  /// Whether a crest with [slug] is on file.
  static bool hasSlug(String slug) => _slugs.contains(slug);

  /// Every slug with a crest on file.
  static Set<String> get slugs => _slugs;

  /// [name] as a lowercase ASCII slug: accents folded (`Ž` is `z`,
  /// `æ` is `ae`), apostrophes dropped, every other run of characters
  /// a hyphen, then the English spellings the providers use mapped to the
  /// crest's own slug.
  static String slugOf(String name) {
    final normalized = _fold(name.toLowerCase())
        .replaceAll(RegExp('[\'\u2019`]'), '')
        .replaceAll(RegExp(r'\s+'), '-')
        .replaceAll(RegExp(r'[^a-z0-9-]+'), '-');
    final slug = normalized
        .replaceAll(RegExp(r'-+'), '-')
        .replaceAll(RegExp(r'^-+|-+$'), '');
    return _englishAliases[slug] ?? slug;
  }

  /// [value] with the letter forms that differ between name sources made
  /// equal: tatweel and marks dropped, hamza forms of alef to alef, teh
  /// marbuta to heh, alef maksura to yeh, repeated spaces to one.
  static String normalizeArabic(String value) => value
      .replaceAll(RegExp('[\u0640\u064B-\u0652]'), '')
      .replaceAll(RegExp('[\u0622\u0623\u0625\u0671]'), '\u0627')
      .replaceAll('\u0629', '\u0647')
      .replaceAll('\u0649', '\u064A')
      .replaceAll('\u0624', '\u0648')
      .replaceAll('\u0626', '\u064A')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();

  static String _fold(String lower) {
    final out = StringBuffer();
    for (final rune in lower.runes) {
      final char = String.fromCharCode(rune);
      out.write(_folds[char] ?? char);
    }
    return out.toString();
  }

